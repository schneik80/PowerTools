def test_variation_points_are_left_out_and_reported():
    """A variant is a choice, not a fitted part.

    Importing every alternative would overstate the assembly -- the RM-500
    carries either an RTK mast or a wire receiver, never both.
    """
    text = """
    package P {
        part def Mast; part def Receiver; part def Base;
        part def Family {
            variation part guidance : Base {
                variant part rtkMast : Mast;
                variant part wireReceiver : Receiver;
            }
        }
        part def Top { part f : Family; }
        part t : Top;
    }
    """

    result = sysml_import.parse(text)
    graph = sysml_import.to_graph(result)

    assert {"parent": "Family", "child": "Mast"} not in graph.edges
    assert {"parent": "Family", "child": "Receiver"} not in graph.edges
    assert any("variation point" in w for w in result.warnings)


