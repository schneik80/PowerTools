# Round trip against the exporter


def test_round_trip_through_the_export_renderer():
    """What Export SysML writes is what this import reads.

    The fixture is generated rather than transcribed, so a change to either the
    emitter or the parser that breaks the pair fails here.
    """
    node = export_model.CompNode
    child = export_model.ChildRef
    nodes = [
        node(
            key="k-top",
            name="Gearbox",
            children=(child("k-hsg", 1), child("k-blk", 2)),
            mass_kg=3.7,
        ),
        node(key="k-hsg", name="Housing (cast)", body_count=1, part_number="PN-1001"),
        node(
            key="k-blk",
            name="Bearing Block",
            body_count=1,
            children=(child("k-shf", 2),),
            is_referenced=True,
        ),
        node(key="k-shf", name="Shaft", body_count=1),
    ]
    assembly = export_model.AssemblyModel(
        meta=export_model.DocMeta(document_name="Gearbox", version=7),
        root_key="k-top",
        nodes={n.key: n for n in nodes},
        joints=(
            export_model.JointEdge(
                name="Pivot",
                joint_type="Revolute",
                owner_key="k-top",
                one_key="k-hsg",
                two_key="k-blk",
            ),
        ),
    )

    text = export_render.sysml_document(assembly)
    graph = parse_graph(text)

    assert graph.root_key == "Gearbox"
    assert {n["key"] for n in graph.nodes} == {
        "Gearbox",
        "Housing (cast)",
        "Bearing Block",
        "Shaft",
    }
    assert graph.edges == [
        {"parent": "Gearbox", "child": "Housing (cast)"},
        {"parent": "Gearbox", "child": "Bearing Block"},
        {"parent": "Bearing Block", "child": "Shaft"},
    ]
    kinds = {n["key"]: n["kind"] for n in graph.nodes}
    assert kinds["Gearbox"] == sysml_import.KIND_ASSEMBLY
    assert kinds["Bearing Block"] == sysml_import.KIND_HYBRID
    assert kinds["Housing (cast)"] == sysml_import.KIND_PART
    assert sorted(graph.collapsed) == [
        "2 x Bearing Block in Gearbox",
        "2 x Shaft in Bearing Block",
    ]
    assert graph.skipped == []
    # The emitter's own joint schema must not import as components. The node-set
    # assertion above is what catches it: `abstract part def FusionComponent`
    # escapes _PART_DEF_RE only because the line starts with the modifier.
    assert "FusionComponent" in text
    assert "FusionComponent" not in {n["key"] for n in graph.nodes}


def test_round_trip_preserves_a_name_that_needed_quoting():
    """Names with spaces, quotes and colons survive the emit-and-read cycle."""
    node = export_model.CompNode
    child = export_model.ChildRef
    hostile = "O'Brien's Bracket (v2): rev/A"
    nodes = [
        node(key="root", name="Top", children=(child("odd", 1),)),
        node(key="odd", name=hostile, body_count=1),
    ]
    assembly = export_model.AssemblyModel(
        meta=export_model.DocMeta(document_name="D"),
        root_key="root",
        nodes={n.key: n for n in nodes},
    )

    graph = parse_graph(export_render.sysml_document(assembly))

    assert {n["name"] for n in graph.nodes} == {"Top", hostile}
    assert graph.edges == [{"parent": "Top", "child": hostile}]


def test_round_trip_of_a_single_child_assembly_reports_nothing_lost():
    node = export_model.CompNode
    child = export_model.ChildRef
    nodes = [
        node(key="root", name="Top", children=(child("leaf", 1),)),
        node(key="leaf", name="Leaf", body_count=1),
    ]
    assembly = export_model.AssemblyModel(
        meta=export_model.DocMeta(document_name="D"),
        root_key="root",
        nodes={n.key: n for n in nodes},
    )

    graph = parse_graph(export_render.sysml_document(assembly))
    summary = sysml_import.summarize(graph)

    assert graph.collapsed == []
    assert graph.skipped == []
    assert graph.warnings == []
    assert "Not imported" not in summary
    assert "Imported 2 components" in summary


