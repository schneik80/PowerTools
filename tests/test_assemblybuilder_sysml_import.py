def test_a_long_summary_is_capped_so_the_dialog_stays_readable():
    """A message box past a couple of dozen lines gets dismissed, not read."""
    kids = " ".join(f"part p{i} : Leaf{i};" for i in range(40))
    defs = " ".join(f"part def Leaf{i};" for i in range(40))
    text = f"package P {{ {defs} part def Top {{ {kids} }} part t : Top; }}"

    graph = parse_graph(text)
    # Force a long list by treating every child as collapsed.
    graph.collapsed = [f"2 x Leaf{i} in Top" for i in range(40)]
    summary = sysml_import.summarize(graph)

    assert "... and 20 more" in summary
    assert summary.count("2 x Leaf") == sysml_import.SUMMARY_LIST_CAP
