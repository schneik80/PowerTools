# Kind inference


def test_structure_infers_the_kind_without_a_classification():
    """A model from another tool carries no classification attribute."""
    text = (
        "package P { part def Leaf { } part def Top { part l : Leaf; } part t : Top; }"
    )

    result = sysml_import.parse(text)

    assert result.definitions["Top"].kind == sysml_import.KIND_ASSEMBLY
    assert result.definitions["Leaf"].kind == sysml_import.KIND_PART


def test_bodies_plus_children_infer_hybrid_without_a_classification():
    text = """
    package P {
        part def Leaf { }
        part def Top { attribute bodyCount : Integer = 2; part l : Leaf; }
        part t : Top;
    }
    """

    assert sysml_import.parse(text).definitions["Top"].kind == sysml_import.KIND_HYBRID


def test_a_leaf_classification_never_wins_over_real_children():
    """A part node has no output port, so its children could not attach.

    A file can contradict itself -- claim a leaf while nesting usages. The
    structure has to win, or the import produces a node whose children are
    silently unconnectable.
    """
    text = """
    package P {
        part def Leaf { }
        part def Top { attribute classification : String = "part"; part l : Leaf; }
        part t : Top;
    }
    """

    result = sysml_import.parse(text)

    assert result.definitions["Top"].kind == sysml_import.KIND_ASSEMBLY
    assert parse_graph(text).edges == [{"parent": "Top", "child": "Leaf"}]


def test_an_unknown_classification_falls_back_to_the_structure():
    text = """
    package P {
        part def Leaf { attribute classification : String = "widget"; }
        part def Top { part l : Leaf; }
        part t : Top;
    }
    """

    assert sysml_import.parse(text).definitions["Leaf"].kind == sysml_import.KIND_PART


