def test_a_non_utf8_file_falls_back_rather_than_refusing(tmp_path):
    """A model saved by another tool on Windows may be cp1252.

    Every byte maps under latin-1, so a mangled accent in one component name is
    a better outcome than refusing the whole import.
    """
    path = tmp_path / "m.sysml"
    path.write_bytes(b"part def 'Halterung \xd812';")

    assert entry._read_sysml_text(str(path)).startswith("part def")


