"""Unit tests for the Assembly Builder's SysML physical view import.

The case that matters most is ``test_round_trip_through_the_export_renderer``:
the importer's whole reason to exist is reading what Export SysML Architecture
Document writes, so the fixture is generated by that renderer rather than typed
out here. A change to either side that breaks the pair fails this test.

Also pinned:

* ``test_a_leaf_classification_never_wins_over_real_children`` -- a ``part``
  node in the editor has no output port, so a definition labelled as a leaf
  that contains usages has to come back as an assembly or its children could
  not be attached.
* ``test_a_definition_that_contains_itself_does_not_recurse`` -- the cycle
  guard, since nothing stops a text file from describing one.
* ``test_multiplicity_above_one_is_reported_not_dropped`` -- Drawflow refuses a
  duplicate parent-to-child link, so quantities are collapsed; the user has to
  be told which ones.
"""

import importlib
from pathlib import Path

import pytest

PT_PKG = Path(__file__).resolve().parent.parent.name
sysml_import = importlib.import_module(
    f"{PT_PKG}.commands.assemblybuilder.sysml_import"
)
export_model = importlib.import_module(f"{PT_PKG}.commands.exportsysml.model")
export_render = importlib.import_module(f"{PT_PKG}.commands.exportsysml.render")


# ---------------------------------------------------------------------------
# Builders


def parse_graph(text):
    """Parse *text* and flatten it, the way ``entry.py`` does."""
    return sysml_import.to_graph(sysml_import.parse(text))


SIMPLE = """
package 'Gearbox Physical View' {
    private import ScalarValues::*;

    part def 'Housing' {
        attribute classification : String = "part";
        attribute bodyCount : Integer = 1;
    }

    part def 'Shaft' {
        attribute classification : String = "part";
        attribute bodyCount : Integer = 1;
    }

    part def 'Bearing Block' {
        attribute classification : String = "hybrid";
        attribute bodyCount : Integer = 1;

        part shaft : 'Shaft'[2];
    }

    part def 'Gearbox' {
        attribute classification : String = "subassembly";

        part housing : 'Housing';
        part bearingBlock : 'Bearing Block';
    }

    part gearbox : 'Gearbox';
}
"""


# ---------------------------------------------------------------------------
# strip_comments


def test_line_comments_are_removed():
    assert "secret" not in sysml_import.strip_comments("part def A; // secret")


def test_block_comments_are_removed():
    assert "secret" not in sysml_import.strip_comments("/* secret */ part def A;")


def test_a_doc_block_is_removed():
    text = "part def A {\n doc\n /* explanatory prose */\n }"
    assert "explanatory" not in sysml_import.strip_comments(text)


def test_comment_markers_inside_a_name_are_kept():
    """A component genuinely named with a slash must survive.

    The exporter quotes names, so ``'A // B'`` is a legal name and not a
    comment. Stripping it would silently rename the user's component.
    """
    text = "part def 'A // B' { }"
    assert "A // B" in sysml_import.strip_comments(text)


def test_comment_markers_inside_a_string_literal_are_kept():
    text = 'attribute description : String = "see /* spec */ page 4";'
    assert "see /* spec */ page 4" in sysml_import.strip_comments(text)


def test_an_unterminated_block_comment_does_not_hang():
    assert sysml_import.strip_comments("part def A; /* never closed") is not None


