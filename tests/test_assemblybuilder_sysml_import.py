def test_the_graph_has_one_node_per_unique_component():
    graph = parse_graph(SIMPLE)

    assert [node["key"] for node in graph.nodes] == [
        "Gearbox",
        "Housing",
        "Bearing Block",
        "Shaft",
    ]
    assert graph.root_key == "Gearbox"


def test_the_root_node_is_flagged_so_the_editor_can_reuse_its_own():
    graph = parse_graph(SIMPLE)

    roots = [node for node in graph.nodes if node["isRoot"]]

    assert len(roots) == 1
    assert roots[0]["key"] == "Gearbox"


def test_edges_follow_containment():
    graph = parse_graph(SIMPLE)

    assert graph.edges == [
        {"parent": "Gearbox", "child": "Housing"},
        {"parent": "Gearbox", "child": "Bearing Block"},
        {"parent": "Bearing Block", "child": "Shaft"},
    ]


def test_multiplicity_above_one_is_reported_not_dropped():
    """Drawflow dedupes a repeated parent-to-child link, so it is collapsed.

    The link still has to exist once, and the user has to learn that the count
    did not survive -- otherwise they build an assembly they believe matches
    the model and it is short two shafts.
    """
    graph = parse_graph(SIMPLE)

    assert {"parent": "Bearing Block", "child": "Shaft"} in graph.edges
    assert graph.collapsed == ["2 x Shaft in Bearing Block"]
    assert "2 x Shaft" in sysml_import.summarize(graph)


def test_a_shared_component_keeps_both_parents():
    """Two parents is how the editor represents a reused component."""
    text = """
    package P {
        part def Pin { }
        part def Left { part p : Pin; }
        part def Right { part p : Pin; }
        part def Top { part l : Left; part r : Right; }
        part t : Top;
    }
    """

    graph = parse_graph(text)

    assert {"parent": "Left", "child": "Pin"} in graph.edges
    assert {"parent": "Right", "child": "Pin"} in graph.edges
    assert len([n for n in graph.nodes if n["key"] == "Pin"]) == 1
    assert "Shared components (more than one parent): 1" in sysml_import.summarize(
        graph
    )


def test_a_repeated_edge_is_emitted_once():
    text = """
    package P {
        part def Pin { }
        part def Top { part a : Pin; part b : Pin; }
        part t : Top;
    }
    """

    graph = parse_graph(text)

    assert graph.edges == [{"parent": "Top", "child": "Pin"}]


def test_a_definition_that_contains_itself_does_not_recurse():
    text = """
    package P {
        part def Loop { part inner : Loop; }
        part def Top { part l : Loop; }
        part t : Top;
    }
    """

    graph = parse_graph(text)

    assert {"parent": "Top", "child": "Loop"} in graph.edges
    assert {"parent": "Loop", "child": "Loop"} not in graph.edges
    assert any("contains itself" in w for w in graph.warnings)


def test_mutual_containment_terminates():
    text = """
    package P {
        part def A { part b : B; }
        part def B { part a : A; }
        part def Top { part a : A; }
        part t : Top;
    }
    """

    graph = parse_graph(text)

    assert graph.root_key == "Top"
    assert len(graph.nodes) == 3


def test_a_usage_of_an_undefined_type_is_reported():
    text = "package P { part def Top { part ghost : Missing; } part t : Top; }"

    graph = parse_graph(text)

    assert graph.edges == []
    assert any("Missing" in item for item in graph.skipped)
    assert "Not imported:" in sysml_import.summarize(graph)


def test_a_component_the_root_does_not_contain_is_skipped():
    """The creation pass only walks down from the root.

    An unreachable definition would arrive as a node wired to nothing and would
    never be built, so it is reported rather than quietly added.
    """
    text = """
    package P {
        part def Orphan { }
        part def Top { }
        part t : Top;
    }
    """

    graph = parse_graph(text)

    assert [node["key"] for node in graph.nodes] == ["Top"]
    assert any("Orphan" in item for item in graph.skipped)


def test_an_external_reference_is_carried_through_and_reported():
    text = """
    package P {
        part def Bought { attribute isExternalReference : Boolean = true; }
        part def Top { part b : Bought; }
        part t : Top;
    }
    """

    graph = parse_graph(text)
    summary = sysml_import.summarize(graph)

    assert [n["isExternalReference"] for n in graph.nodes if n["key"] == "Bought"] == [
        True
    ]
    assert "linked from other documents" in summary


def test_an_unparseable_file_summarises_the_failure():
    graph = parse_graph("this is not a model at all")

    assert graph.root_key == ""
    assert graph.nodes == []
    assert "No component structure" in sysml_import.summarize(graph)


def test_every_node_kind_is_one_the_editor_knows():
    graph = parse_graph(SIMPLE)

    assert {node["kind"] for node in graph.nodes} <= {
        sysml_import.KIND_PART,
        sysml_import.KIND_ASSEMBLY,
        sysml_import.KIND_HYBRID,
    }


def test_no_edge_points_at_a_part_node():
    """A part node has no output port, so it can never be a parent."""
    graph = parse_graph(SIMPLE)
    kinds = {node["key"]: node["kind"] for node in graph.nodes}

    for edge in graph.edges:
        assert kinds[edge["parent"]] != sysml_import.KIND_PART, edge


